export function getHeader($) {
  return $('header.main-navigation');
}

export function getNav($) {
  return $('header nav');
}

export function getBrand($) {
  return $('header .blog-name');
}

export function getLogo($) {
  return $('header .blog-name img.blog-logo');
}

export function getNavLinks($) {
  return $('header .menu-items a');
}

export function getNavToggle($) {
  return $('header .nav-toggle');
}

export function getMenu($) {
  return $('header #nav-menu');
}
